const {chromium} = require('playwright');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--no-proxy-server']});
 const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 const page=await context.newPage();page.setDefaultTimeout(12000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.JOURNAL_URL;
 if (!base || !process.env.JOURNAL_EMAIL || !process.env.JOURNAL_PASSWORD) throw new Error('Set JOURNAL_URL, JOURNAL_EMAIL and JOURNAL_PASSWORD for an isolated test account');
 await page.goto(base+'/users/log-in');
 await page.getByLabel('Email').fill(process.env.JOURNAL_EMAIL);
 await page.getByLabel('Password',{exact:true}).fill(process.env.JOURNAL_PASSWORD);
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.waitForURL('**/app/today');
 await page.getByRole('link',{name:'Log stool',exact:true}).click();
 await page.waitForSelector('#entry-form');
 await page.getByLabel('Notes',{exact:true}).fill('Browser draft unicode 饭');
 await page.getByLabel('Bristol type').selectOption('4');
 await page.waitForTimeout(300);
 page.once('dialog',d=>d.accept());await page.reload();
 await page.waitForFunction(()=>document.querySelector('textarea')?.value==='Browser draft unicode 饭');
 if(await page.getByLabel('Bristol type').inputValue()!=='4') throw new Error('Rating draft missing');
 await page.getByRole('button',{name:'Save entry',exact:true}).click();
 await page.waitForURL(/\/app\/entries\/\d+$/);
 await page.getByText('Browser draft unicode 饭',{exact:true}).waitFor();
 if(await page.evaluate(()=>Object.keys(sessionStorage).some(k=>k.startsWith('health-journal:draft:')))) throw new Error('Draft not cleared on save');
 await page.getByRole('link',{name:'Today',exact:true}).click();
 await page.getByRole('link',{name:'How I feel',exact:true}).click();
 await page.getByLabel('Bloating').selectOption('0');
 await page.getByRole('button',{name:'Save entry',exact:true}).click();
 await page.waitForURL(/\/app\/entries\/\d+$/);
 await page.getByRole('link',{name:'Settings',exact:true}).click();
 await page.getByLabel('Timezone',{exact:true}).fill('America/Chicago');
 await page.getByRole('checkbox',{name:'Hide image previews'}).check();
 await page.getByRole('button',{name:'Save preferences'}).click();
 await page.getByText('Settings saved.',{exact:true}).waitFor();
 await page.getByRole('link',{name:'Today',exact:true}).click();
 await page.waitForFunction(()=>document.getElementById('connection-status').hidden);
 await context.setOffline(true);await page.locator('#connection-status').waitFor({state:'visible'});
 await context.setOffline(false);await page.waitForFunction(()=>document.getElementById('connection-status').hidden);
 await page.screenshot({path:process.env.JOURNAL_SCREENSHOT || '/tmp/health-journal-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow) throw new Error('Horizontal mobile overflow');
 await page.getByRole('link',{name:'Add note',exact:true}).click();
 await page.getByLabel('Notes',{exact:true}).fill('Unsaved logout draft');
 page.on('dialog',dialog=>dialog.accept());
 await page.getByRole('link',{name:'Settings',exact:true}).click();
 await page.getByRole('link',{name:'Log out and clear drafts in this tab'}).click();
 await page.waitForURL('**/users/log-in');
 if(await page.evaluate(()=>Object.keys(sessionStorage).some(k=>k.startsWith('health-journal:draft:')))) throw new Error('Logout left a draft');
 if(errors.length) throw new Error(errors.join('\n'));
 console.log('PASS: mobile login, stool save, check-in zero, draft reload/clear, settings, logout offline/reconnect indication and no horizontal overflow.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
